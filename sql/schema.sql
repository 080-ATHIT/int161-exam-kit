CREATE TABLE IF NOT EXISTS brands (
 id INT PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(100) NOT NULL UNIQUE,
 country_of_origin VARCHAR(100), website VARCHAR(200),
 is_active TINYINT NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS products (
 id INT PRIMARY KEY AUTO_INCREMENT, sku VARCHAR(50) NOT NULL UNIQUE,
 name VARCHAR(150) NOT NULL, brand_id INT NOT NULL,
 category VARCHAR(50) NOT NULL, price DECIMAL(10,2) NOT NULL,
 ram_gb INT NOT NULL, storage_gb INT NOT NULL, color VARCHAR(50) NOT NULL, stock_quantity INT NOT NULL DEFAULT 0,
 status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE', release_date DATE,
 internal_cost DECIMAL(10,2),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT kit_fk_brand FOREIGN KEY (brand_id) REFERENCES brands(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS tags (
 code VARCHAR(32) PRIMARY KEY, label VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS product_tags (
 product_id INT NOT NULL, tag_code VARCHAR(32) NOT NULL,
 PRIMARY KEY(product_id,tag_code),
 CONSTRAINT kit_fk_product FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE RESTRICT,
 CONSTRAINT kit_fk_tag FOREIGN KEY(tag_code) REFERENCES tags(code) ON DELETE RESTRICT
);
